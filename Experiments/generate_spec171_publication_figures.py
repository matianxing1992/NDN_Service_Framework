#!/usr/bin/env python3
"""Generate publication figures from the frozen Spec171 evidence.

The mobility holdout figure is generated by ``analyze_mobility_comparison.py``.
This companion figure renders the independently repeated capacity-matched
multi-Provider work-efficiency result from its machine-readable aggregate.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt


COLORS = {
    "NDNSF": "#2864d7",
    "gRPC-PAR-4": "#d97706",
    "NSC-4": "#6b7280",
}


def load_work_efficiency(path: Path) -> dict:
    report = json.loads(path.read_text(encoding="utf-8"))
    if report.get("claim_verdict") != (
            "NDNSF_MULTIPROVIDER_WORK_EFFICIENCY_ADVANTAGE_CONFIRMED"):
        raise ValueError("unexpected work-efficiency claim verdict")
    success = report["success"]
    work = report["provider_work"]
    requests = int(report["requests_per_system"])
    return {
        "requests": requests,
        "systems": ["NDNSF", "gRPC-PAR-4", "NSC-4"],
        "success_pct": [
            100.0 * success["ndnsf"] / requests,
            100.0 * success["grpc_par_4"] / requests,
            100.0 * success["nsc_4"] / requests,
        ],
        "executions_per_request": [
            work["ndnsf_provider_executions"] / requests,
            work["grpc_server_handler_executions_snapshot_exact"] / requests,
            # The combined aggregate does not include a pooled NSC attempt
            # count.  The six-seed paper table reports 1,804 attempts.
            1804 / requests,
        ],
        "execution_ratio": work["ndnsf_to_grpc_execution_ratio"],
        "success_ci_pp": success["bootstrap_95_percent_points"],
        "seeds": report["seeds"],
    }


def write_figure(report: dict, output_dir: Path) -> list[Path]:
    output_dir.mkdir(parents=True, exist_ok=True)
    systems = report["systems"]
    colors = [COLORS[item] for item in systems]
    fig, axes = plt.subplots(1, 2, figsize=(10.8, 4.2), constrained_layout=True)
    fig.suptitle(
        "Capacity-matched four-Provider work efficiency",
        fontsize=16, fontweight="bold")
    x = list(range(len(systems)))

    ax = axes[0]
    bars = ax.bar(x, report["success_pct"], color=colors, width=0.62,
                  edgecolor="#222222", linewidth=0.6)
    ax.set_title("Logical success", fontsize=12)
    ax.set_ylabel("Success rate (%)")
    ax.set_ylim(98.8, 100.12)
    ax.set_xticks(x, systems, rotation=18, ha="right")
    ax.grid(axis="y", color="#d8dce3", linewidth=0.7)
    ax.set_axisbelow(True)
    for bar, value in zip(bars, report["success_pct"]):
        ax.text(bar.get_x() + bar.get_width() / 2, value + 0.03,
                f"{value:.2f}%", ha="center", va="bottom", fontsize=9)
    lo, hi = report["success_ci_pp"]
    ax.text(0.02, 0.02,
            f"NDNSF − gRPC paired 95% CI: [{lo:.2f}, {hi:.2f}] pp",
            transform=ax.transAxes, fontsize=8, color="#444444")

    ax = axes[1]
    bars = ax.bar(x, report["executions_per_request"], color=colors, width=0.62,
                  edgecolor="#222222", linewidth=0.6)
    ax.set_title("Provider/server execution work", fontsize=12)
    ax.set_ylabel("Executions per logical request")
    ax.set_ylim(0, 4.35)
    ax.set_xticks(x, systems, rotation=18, ha="right")
    ax.grid(axis="y", color="#d8dce3", linewidth=0.7)
    ax.set_axisbelow(True)
    for bar, value in zip(bars, report["executions_per_request"]):
        ax.text(bar.get_x() + bar.get_width() / 2, value + 0.08,
                f"{value:.3f}", ha="center", va="bottom", fontsize=9)
    ax.text(0.02, 0.02,
            f"NDNSF/gRPC work ratio: {report['execution_ratio']:.4f}",
            transform=ax.transAxes, fontsize=8, color="#444444")

    fig.text(
        0.5, -0.015,
        "Six paired seeds (20–25), 1,800 requests/system; no latency claim.",
        ha="center", va="bottom", fontsize=9, color="#444444")

    paths = []
    for suffix in ("png", "pdf", "svg"):
        path = output_dir / f"provider-work-efficiency.{suffix}"
        fig.savefig(path, dpi=300 if suffix == "png" else None,
                    bbox_inches="tight")
        paths.append(path)
    plt.close(fig)
    return paths


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--aggregate", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    report = load_work_efficiency(args.aggregate)
    paths = write_figure(report, args.output_dir)
    print(json.dumps({
        "requests": report["requests"],
        "seeds": report["seeds"],
        "execution_ratio": report["execution_ratio"],
        "outputs": [str(path.resolve()) for path in paths],
    }, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
